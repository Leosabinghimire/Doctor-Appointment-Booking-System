const generateSlots = (count: number, available = true): TimeSlot[] => {
  const times = [
    '09:00 AM',
    '09:30 AM',
    '10:00 AM',
    '10:30 AM',
    '11:00 AM',
    '11:30 AM',
    '01:00 PM',
    '01:30 PM',
    '02:00 PM',
    '02:30 PM',
    '03:00 PM',
    '03:30 PM',
    '04:00 PM',
    '04:30 PM',
    '05:00 PM',
  ];
  return times.slice(0, count).map((time, i) => ({
    id: `slot-${i}-${time}`,
    time,
    available: available && Math.random() > 0.25,
  }));
};

